import { describe, expect, it } from "vitest";
import { render, postProcess } from "../render.js";
import { buildIr } from "../ir.js";
import type { CanvasDocument, ContainerNode, Node } from "../../../shared/document.js";
import { createDefaultTheme } from "../../../shared/theme.js";
import { BUILTIN_DEVICES } from "../../../shared/device.js";
import {
	ALL_DESCRIPTORS,
	type ComponentDescriptor,
} from "../../../client/palette/catalog.js";

function makeDoc(nodes: Node[], rootId: string): CanvasDocument {
	const root = nodes.find((n) => n.id === rootId) as ContainerNode;
	return {
		version: 1,
		id: "d1",
		name: "Test",
		createdAt: 0,
		updatedAt: 0,
		root,
		nodes: Object.fromEntries(nodes.map((n) => [n.id, n])),
		theme: createDefaultTheme(),
		devices: BUILTIN_DEVICES,
		activeDeviceId: "phone",
	};
}

/** 为 descriptor 创建单节点文档。 */
function makeDocForDescriptor(descriptor: ComponentDescriptor): CanvasDocument {
	const props: Record<string, unknown> = {};
	for (const schema of descriptor.defaultProps) {
		if ("default" in schema && schema.default !== undefined) {
			props[schema.key] = schema.default;
		}
	}
	const node: Node = { id: "root", type: descriptor.id, props };
	if (descriptor.codegen.render !== "leaf") {
		(node as ContainerNode).children = [];
	}
	return makeDoc([node], "root");
}

/** Scaffold > Column > [Text, Button] 示例文档。 */
function makeSampleDoc(): CanvasDocument {
	return makeDoc(
		[
			{ id: "root", type: "m3.Scaffold", props: {}, children: ["col"] },
			{ id: "col", type: "layout.Column", props: { spacing: 8 }, children: ["t1", "btn"] },
			{ id: "t1", type: "m3.Text", props: { text: "Submit" } },
			{ id: "btn", type: "m3.Button", props: {}, children: [] },
		],
		"root",
	);
}

describe("render", () => {
	it("生成文件头与 package", () => {
		const [file] = render(buildIr(makeSampleDoc()));
		expect(file.source).toContain(
			"// Generated by dsh-compose-studio. Do not edit manually.",
		);
		expect(file.source).toContain("package com.example.generated");
	});

	it("imports 汇总且无冗余", () => {
		const [file] = render(buildIr(makeSampleDoc()));
		const importLines = file.source
			.split("\n")
			.filter((l) => l.startsWith("import "));
		const unique = new Set(importLines);
		expect(importLines.length).toBe(unique.size);
		// 核心 import 存在
		expect(file.source).toContain("import androidx.compose.material3.Scaffold");
		expect(file.source).toContain("import androidx.compose.material3.Button");
		expect(file.source).toContain("import androidx.compose.runtime.Composable");
		expect(file.source).toContain("import androidx.compose.ui.Modifier");
	});

	it("@Composable 拆分：GeneratedScreen + GeneratedContent", () => {
		const [file] = render(buildIr(makeSampleDoc()));
		expect(file.source).toContain("fun GeneratedScreen(modifier: Modifier = Modifier)");
		expect(file.source).toContain("private fun GeneratedContent(");
	});

	it("事件提升：onClick → handle<Component>Click 参数", () => {
		const [file] = render(buildIr(makeSampleDoc()));
		expect(file.source).toContain("handleButtonClick: () -> Unit");
		expect(file.source).toContain("onClick = handleButtonClick");
		// 调用处传 lambda
		expect(file.source).toContain("handleButtonClick = {");
	});

	it("多个同类事件参数名不重复（Button + OutlinedButton）", () => {
		const doc = makeDoc(
			[
				{ id: "root", type: "m3.Scaffold", props: {}, children: ["col"] },
				{ id: "col", type: "layout.Column", props: {}, children: ["b1", "b2", "b3"] },
				{ id: "b1", type: "m3.Button", props: {}, children: [] },
				{ id: "b2", type: "m3.Button", props: {}, children: [] },
				{ id: "b3", type: "m3.OutlinedButton", props: {}, children: [] },
			],
			"root",
		);
		const [file] = render(buildIr(doc));
		// 三个按钮事件参数名唯一
		expect(file.source).toContain("handleButtonClick: () -> Unit");
		expect(file.source).toContain("handleButtonClick2: () -> Unit");
		expect(file.source).toContain("handleOutlinedButtonClick: () -> Unit");
		// 无重复参数名（Kotlin 语法合法）
		const sig = file.source
			.split("\n")
			.find((l) => l.includes("private fun") && l.includes("handleButtonClick"));
		expect(sig).toBeDefined();
		const paramNames = (sig!.match(/handle\w+/g) ?? []);
		expect(new Set(paramNames).size).toBe(paramNames.length);
	});

	it("Column spacing → Arrangement.spacedBy", () => {
		const [file] = render(buildIr(makeSampleDoc()));
		expect(file.source).toContain(
			"verticalArrangement = Arrangement.spacedBy(8.dp)",
		);
		expect(file.source).toContain(
			"import androidx.compose.foundation.layout.Arrangement",
		);
	});

	it("Modifier 顺序：width → height → padding → background", () => {
		const doc = makeDoc(
			[
				{
					id: "root",
					type: "m3.Scaffold",
					props: {},
					children: ["box"],
				},
				{
					id: "box",
					type: "layout.Box",
					props: {
						modifierWidth: 100,
						modifierHeight: 50,
						modifierPadding: 16,
						modifierBackground: "#6750A4",
					},
					children: [],
				},
			],
			"root",
		);
		const [file] = render(buildIr(doc));
		const modifierLine = file.source
			.split("\n")
			.find((l) => l.includes("modifier = Modifier."));
		expect(modifierLine).toBeDefined();
		// 顺序：width 在 height 前，height 在 padding 前，padding 在 background 前
		const w = modifierLine!.indexOf(".width(");
		const h = modifierLine!.indexOf(".height(");
		const p = modifierLine!.indexOf(".padding(");
		const b = modifierLine!.indexOf(".background(");
		expect(w).toBeGreaterThanOrEqual(0);
		expect(h).toBeGreaterThan(w);
		expect(p).toBeGreaterThan(h);
		expect(b).toBeGreaterThan(p);
	});

	it("KDoc 含 Root 说明", () => {
		const [file] = render(buildIr(makeSampleDoc()));
		expect(file.source).toContain(" * Root: Scaffold");
	});

	it("事件 TODO 注释", () => {
		const [file] = render(buildIr(makeSampleDoc()));
		expect(file.source).toContain("/* TODO");
	});

	it("slot 类型组件无子节点生成空 lambda", () => {
		const doc = makeDoc(
			[
				{ id: "root", type: "layout.Column", props: {}, children: ["btn"] },
				{ id: "btn", type: "m3.Button", props: {}, children: [] },
			],
			"root",
		);
		const [file] = render(buildIr(doc));
		expect(file.source).toMatch(/Button\([^)]*\)\s*\{\s*\}/);
	});

	it("postProcess 移除多余空行", () => {
		expect(postProcess("a\n\n\n\nb\n")).toBe("a\n\nb\n");
		expect(postProcess("a  \nb\t\n")).toBe("a\nb\n");
	});

	it("纯函数：相同输入相同输出", () => {
		const doc = makeSampleDoc();
		const a = render(buildIr(doc));
		const b = render(buildIr(doc));
		expect(a).toEqual(b);
	});

	it("未知组件降级为 Box 仍生成代码", () => {
		const doc = makeDoc(
			[
				{ id: "root", type: "m3.Scaffold", props: {}, children: ["unk"] },
				{ id: "unk", type: "unknown.Foo", props: {}, children: [] },
			],
			"root",
		);
		const [file] = render(buildIr(doc));
		expect(file.source).toContain("Box(");
	});
});

describe("Column/Row 排列与对齐", () => {
	it("Column：arrangement 合并 spacing + alignment", () => {
		const doc = makeDoc(
			[
				{
					id: "root",
					type: "layout.Column",
					props: {
						spacing: 8,
						verticalArrangement: "spaceBetween",
						horizontalAlignment: "center",
					},
					children: [],
				},
			],
			"root",
		);
		const [file] = render(buildIr(doc));
		expect(file.source).toContain(
			"verticalArrangement = Arrangement.SpaceBetween.spacedBy(8.dp)",
		);
		expect(file.source).toContain(
			"horizontalAlignment = Alignment.CenterHorizontally",
		);
		expect(file.source).toContain("import androidx.compose.ui.Alignment");
	});

	it("Row：arrangement + verticalAlignment", () => {
		const doc = makeDoc(
			[
				{
					id: "root",
					type: "layout.Row",
					props: {
						spacing: 8,
						horizontalArrangement: "center",
						verticalAlignment: "end",
					},
					children: [],
				},
			],
			"root",
		);
		const [file] = render(buildIr(doc));
		expect(file.source).toContain(
			"horizontalArrangement = Arrangement.Center.spacedBy(8.dp)",
		);
		expect(file.source).toContain("verticalAlignment = Alignment.Bottom");
	});

	it("默认 arrangement 不生成额外参数（避免重复）", () => {
		const doc = makeDoc(
			[
				{
					id: "root",
					type: "layout.Column",
					props: { spacing: 8, verticalArrangement: "top" },
					children: [],
				},
			],
			"root",
		);
		const [file] = render(buildIr(doc));
		expect(file.source).toContain(
			"verticalArrangement = Arrangement.spacedBy(8.dp)",
		);
		// 不应出现重复的 verticalArrangement
		expect(
			file.source.match(/verticalArrangement = /g)?.length ?? 0,
		).toBe(1);
	});

	it("Button text → Text 内容", () => {
		const doc = makeDoc(
			[
				{
					id: "root",
					type: "layout.Column",
					props: {},
					children: ["btn"],
				},
				{
					id: "btn",
					type: "m3.Button",
					props: { text: "Submit" },
					children: [],
				},
			],
			"root",
		);
		const [file] = render(buildIr(doc));
		expect(file.source).toContain('Text(text = "Submit")');
		expect(file.source).toContain("Button(");
		// text 不作为 Button 参数（而是 content 内的 Text）
		expect(file.source).not.toContain("Button(text =");
	});

	it("Scaffold 槽：TopAppBar/内容分组渲染（结构快照）", () => {
		const doc = makeDoc(
			[
				{ id: "root", type: "m3.Scaffold", props: {}, children: ["bar", "col"] },
				{ id: "bar", type: "m3.TopAppBar", props: { title: "App" }, children: [] },
				{ id: "col", type: "layout.Column", props: {}, children: [] },
			],
			"root",
		);
		const [file] = render(buildIr(doc));
		expect(file.source).toContain("Scaffold(");
		expect(file.source).toContain("TopAppBar(");
	});
});

describe("render 快照：全部内置组件", () => {
	for (const descriptor of ALL_DESCRIPTORS) {
		it(`快照 ${descriptor.id}`, () => {
			const doc = makeDocForDescriptor(descriptor);
			const [file] = render(buildIr(doc));
			expect(file.source).toMatchSnapshot();
		});
	}
});
